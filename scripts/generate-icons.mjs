/** Regenerate all HiveTeX icon assets from the canonical native SVG. */
import { readFile, writeFile, copyFile, mkdir, rm, realpath } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const icons = join(root, 'apps/desktop/src-tauri/icons');
const cli = join(root, 'apps/desktop/node_modules/@tauri-apps/cli/tauri.js');
const source = await readFile(join(icons, 'source.svg'), 'utf8');
const paths = [...source.matchAll(/<path[^>]*d="([^"]+)"[^>]*\/>/g)].map(m => m[1]);
if (paths.length !== 3) throw new Error('Expected the two stems and center bridge in source.svg');
const [left, right, bridge] = paths;
const smallBridge = bridge.slice(0, bridge.indexOf('Z') + 1);
const small = source.replace(bridge, smallBridge);
await writeFile(join(icons, 'source-small.svg'), small);
execFileSync(process.execPath, [cli, 'icon', 'src-tauri/icons/source.svg'], { cwd: join(root, 'apps/desktop'), stdio: 'inherit' });
const tmp = join(icons, '.small');
await mkdir(tmp, { recursive: true });
execFileSync(process.execPath, [cli, 'icon', 'src-tauri/icons/source-small.svg', '-o', tmp, '-p', '16', '-p', '24'], { cwd: join(root, 'apps/desktop'), stdio: 'inherit' });
// ICO entries can contain PNG data. Keep the large generated entries, add simplified 16/24px entries.
const ico = await readFile(join(icons, 'icon.ico'));
const entries = [];
for (let i = 0; i < ico.readUInt16LE(4); i++) {
  const offset = 6 + i * 16;
  const width = ico[offset] || 256;
  if (width <= 24) continue;
  entries.push({ width, header: Buffer.from(ico.subarray(offset, offset + 16)), data: ico.subarray(ico.readUInt32LE(offset + 12), ico.readUInt32LE(offset + 12) + ico.readUInt32LE(offset + 8)) });
}
for (const width of [16, 24]) {
  const header = Buffer.alloc(16);
  header[0] = width; header[1] = width;
  header.writeUInt16LE(1, 4); header.writeUInt16LE(32, 6);
  entries.push({ width, header, data: await readFile(join(tmp, width + 'x' + width + '.png')) });
}
entries.sort((a, b) => a.width - b.width);
const header = Buffer.alloc(6); header.writeUInt16LE(1, 2); header.writeUInt16LE(entries.length, 4);
let offset = 6 + entries.length * 16;
for (const entry of entries) { entry.header.writeUInt32LE(entry.data.length, 8); entry.header.writeUInt32LE(offset, 12); offset += entry.data.length; }
await writeFile(join(icons, 'icon.ico'), Buffer.concat([header, ...entries.map(e => e.header), ...entries.map(e => e.data)]));
await copyFile(join(icons, 'icon.png'), join(root, 'apps/desktop/app-icon.png'));
const rect = source.match(/<rect[^>]+\/>/)[0];
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><style>.small{display:none}@media(max-width:24px){.large{display:none}.small{display:inline}}</style>${rect}<g fill="#EBA724"><path d="${left}"/><path d="${right}"/></g><path class="large" fill="#FFF4D6" fill-rule="evenodd" d="${bridge}"/><path class="small" fill="#FFF4D6" d="${smallBridge}"/></svg>\n`;
await writeFile(join(root, 'apps/web/public/favicon.svg'), favicon);
const logo = `<script lang="ts">
  // Generated by scripts/generate-icons.mjs from icons/source.svg.
  let { size = 24, word = true }: { size?: number; word?: boolean } = $props();
</script>
<span class="hx-logo">
  <svg width={size} height={size} viewBox="128 112 768 800" aria-hidden="true" focusable="false">
    <g fill="var(--honey-ink)"><path d="${left}"/><path d="${right}"/></g>
    <path fill="var(--ink)" fill-rule="evenodd" d={size <= 24 ? '${smallBridge}' : '${bridge}'} />
  </svg>
  {#if word}<span class="word">HiveTeX</span>{/if}
</span>
<style>
  .hx-logo { display: inline-flex; align-items: center; gap: 8px; color: var(--ink); font-weight: 700; font-size: var(--text-lg); letter-spacing: -0.01em; }
</style>
`;
await writeFile(join(root, 'apps/web/src/ui/Logo.svelte'), logo);
const actual = await realpath(tmp);
if (actual.toLowerCase() !== (await realpath(icons)).toLowerCase() + '/.small' && actual.replaceAll('\\', '/').toLowerCase() !== (await realpath(icons)).replaceAll('\\', '/').toLowerCase() + '/.small') throw new Error('Unexpected temporary icon directory');
await rm(actual, { recursive: true, force: true });
