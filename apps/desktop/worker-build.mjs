/**
 * Bundles the headless sync worker into one ES module for the pinned Node runtime (worker.config.json). The output is a
 * packaged resource of the desktop app; nothing is resolved from node_modules at run time.
 * Usage: node worker-build.mjs [outfile]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const cfg = JSON.parse(readFileSync(resolve(here, 'worker.config.json'), 'utf8'));
const major = cfg.node.split('.')[0];
export async function buildWorker(outfile = resolve(here, cfg.out)) {
  await build({
    entryPoints: [resolve(here, cfg.entry)],
    outfile,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: `node${major}`,
    sourcemap: false,
    legalComments: 'eof',
    banner: { js: `// HiveTeX sync worker for Node ${cfg.node} (generated by apps/desktop/worker-build.mjs)` },
    logLevel: 'warning',
    // Reported to co-authors in connection tests (the worker starts with a cleared environment).
    define: { 'process.env.HIVETEX_VERSION': JSON.stringify(JSON.parse(readFileSync(resolve(here, 'package.json'), 'utf8')).version) },
  });
  // Checked by the app before every worker start (worker.rs `verify`): a tampered or half-updated bundle never runs.
  const sha256 = createHash('sha256').update(readFileSync(outfile)).digest('hex');
  writeFileSync(resolve(dirname(outfile), 'manifest.json'), JSON.stringify({ node: cfg.node, script: 'hivetex-worker.mjs', sha256 }, null, 2) + '\n');
  return outfile;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const out = await buildWorker(process.argv[2] ? resolve(process.argv[2]) : undefined);
  console.log(`worker bundle: ${out}`);
}
